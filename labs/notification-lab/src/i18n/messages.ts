const INTL: Record<Locale, string> = { pt: "pt-BR", en: "en-US", es: "es-ES" };

export function formatDateKey(locale: Locale, date: string | undefined): string {
  if (!date) return "";
  const [y, m, d] = date.split("-").map(Number) as [number, number, number];
  return new Intl.DateTimeFormat(INTL[locale], { weekday: "short", day: "numeric", month: "short", timeZone: "UTC" }).format(new Date(Date.UTC(y, m - 1, d)));
}

export function formatClock(locale: Locale, epoch: number, timeZone: string, withDate = false): string {
  return new Intl.DateTimeFormat(INTL[locale], {
    timeZone,
    hour: "2-digit",
    minute: "2-digit",
    second: withDate ? undefined : "2-digit",
    ...(withDate ? { weekday: "short", day: "numeric", month: "short" } : {}),
    hourCycle: "h23",
  }).format(new Date(epoch));
}

export function formatDay(locale: Locale, epoch: number, timeZone: string): string {
  return new Intl.DateTimeFormat(INTL[locale], { timeZone, weekday: "long", day: "numeric", month: "long" }).format(new Date(epoch));
}

export function notificationCopy(locale: Locale, event: NotificationEvent): Copy {
  const copy = NOTIFY[locale][event.type];
  const p: EventParams = event.params;
  const params = {
    ...p,
    date: formatDateKey(locale, p.date),
    fromDate: formatDateKey(locale, p.fromDate),
    issue: p.issue ? ISSUE[locale][p.issue] : "",
  };
  return { title: fill(copy.title, params), body: fill(copy.body, params) };
}

