export function describeCommand(locale: Locale, cmd: Command, w: World): string {
  const name = (id: string | null | undefined) => (id ? w.users[id]?.displayName ?? id : ui(locale, "noAccount"));
  const job = "jobId" in cmd ? w.jobs[cmd.jobId]?.propertyName ?? cmd.jobId : "";
  const device = "deviceId" in cmd && cmd.deviceId ? w.devices[cmd.deviceId]?.label ?? cmd.deviceId : "";
  const join = (ids: string[]) => ids.map(name).join(", ");
  let key: string = cmd.type;
  const p: Record<string, string> = { job, device };
  switch (cmd.type) {
    case "SEND_OFFER":
      p.mode = ui(locale, cmd.mode === "AUTO" ? "autoMode" : "manualMode");
      p.who = join(cmd.cleanerIds);
      break;
    case "RESPOND_OFFER":
      key = `RESPOND_OFFER_${cmd.response}`;
      p.who = name(cmd.cleanerId);
      break;
    case "RACE_ACCEPT":
      p.who = join(cmd.cleanerIds);
      break;
    case "ASSIGN":
    case "REPLACE_CLEANER":
    case "CONFIRM_ATTENDANCE":
    case "CHECKLIST_SUBMIT":
    case "REPORT_ISSUE":
    case "SPECIAL_REQUEST":
      p.who = name(cmd.cleanerId);
      break;
    case "RESCHEDULE":
      p.date = formatDateKey(locale, cmd.date);
      p.time = cmd.start;
      break;
    case "SET_CLOCK":
      p.date = formatDateKey(locale, cmd.date);
      p.time = cmd.time;
      break;
    case "RUN_REMINDER":
      p.kind = cmd.kind;
      break;
    case "REVOKE_ACCESS":
      p.who = name(cmd.userId);
      break;
    case "SWITCH_ACCOUNT":
      p.who = name(cmd.userId);
      break;
    case "SET_ONLINE":
      p.state = ui(locale, cmd.online ? "online" : "offline");
      break;
    case "SET_PROVIDER_ALL":
      p.mode = cmd.mode;
      break;
    default:
      break;
  }
  return fill(CMD[locale][key] ?? key, p);
}

